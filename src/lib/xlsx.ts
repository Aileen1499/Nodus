export type Cell = { v?: string | number; f?: string; style?: 'title' | 'head' | 'input' | 'note' | 'result' | 'money' | 'inputMoney' };
export type Row = Cell[];

const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const col = (i: number) => String.fromCharCode(65 + i);

const STYLE_ID: Record<NonNullable<Cell['style']> | 'none', number> = { none: 0, title: 1, head: 2, input: 3, note: 4, result: 5, money: 6, inputMoney: 7 };

const sheetXml = (rows: Row[], widths: number[]): string => {
  const cols = widths.map((w, i) => `<col min="${i + 1}" max="${i + 1}" width="${w}" customWidth="1"/>`).join('');
  const body = rows
    .map((r, ri) => {
      const cells = r
        .map((c, ci) => {
          const ref = `${col(ci)}${ri + 1}`;
          const s = STYLE_ID[c.style ?? 'none'];
          if (c.f) return `<c r="${ref}" s="${s}"><f>${esc(c.f)}</f></c>`;
          if (typeof c.v === 'number') return `<c r="${ref}" s="${s}"><v>${c.v}</v></c>`;
          if (typeof c.v === 'string' && c.v !== '') return `<c r="${ref}" s="${s}" t="inlineStr"><is><t xml:space="preserve">${esc(c.v)}</t></is></c>`;
          return s ? `<c r="${ref}" s="${s}"/>` : '';
        })
        .join('');
      return `<row r="${ri + 1}">${cells}</row>`;
    })
    .join('');
  return `<?xml version="1.0" encoding="UTF-8" standalone="yes"?><worksheet xmlns="http://schemas.openxmlformats.org/spreadsheetml/2006/main"><cols>${cols}</cols><sheetData>${body}</sheetData></worksheet>`;
};

